-- Sesiones vencidas y no canceladas; la ultima de algunos grupos queda sin registro (cumplimiento del docente)
SELECT s.id, s.grupo, s.fechaHoraInicio, s.fechaHoraFin, g.docente,
       rnDesc = ROW_NUMBER() OVER (PARTITION BY s.grupo ORDER BY s.fechaHoraInicio DESC)
INTO #ses
FROM dbo.Sesion s JOIN dbo.Grupo g ON g.id = s.grupo
WHERE s.fechaHoraFin < @corte AND NOT EXISTS (SELECT 1 FROM dbo.SesionCancelacion sc WHERE sc.sesion = s.id);
DELETE FROM #ses WHERE rnDesc = 1 AND grupo IN ('BC3BC734-ED4D-5064-8D5A-9F33B5969C6D', '885AC31C-1D6F-58AA-95C0-4625B80CFD8C');
;WITH r AS (SELECT *, rn2 = ROW_NUMBER() OVER (PARTITION BY grupo ORDER BY fechaHoraInicio DESC) FROM #ses) UPDATE r SET rnDesc = rn2;

BEGIN TRANSACTION;
SELECT idToma = NEWID(), s.id AS sesion, s.fechaHoraInicio, s.fechaHoraFin, s.docente, s.rnDesc,
       esQr = IIF(ABS(CHECKSUM(s.id)) % 3 = 0, 1, 0)
INTO #toma FROM #ses s;
INSERT INTO dbo.TomaAsistencia (id, sesion, numero, modo, estado, esImplicita, docenteApertura, fechaAperturaUtc, fechaCierreUtc,
                                totalAusentesMarcados, idCorrelacionApertura, idCorrelacionCierre)
SELECT t.idToma, t.sesion, 1, IIF(t.esQr = 1, @mQr, @mManual), @eCerrada, 0, t.docente, DATEADD(MINUTE, 5, t.fechaHoraInicio),
       DATEADD(MINUTE, 20, t.fechaHoraInicio), 0, NEWID(), NEWID()
FROM #toma t;

SELECT idAsistencia = NEWID(), eg.id AS eg, t.idToma, t.sesion, t.fechaHoraInicio, t.fechaHoraFin, t.esQr,
       forzar = IIF(ta.forzada = 1 AND t.rnDesc = 1, 1, 0), ta.pct, ta.ex,
       n = COUNT(*) OVER (PARTITION BY eg.id)
INTO #m
FROM #toma t JOIN dbo.Sesion s ON s.id = t.sesion JOIN dbo.EstudianteGrupo eg ON eg.grupo = s.grupo JOIN #tasa ta ON ta.eg = eg.id;
SELECT m.*, rn = ROW_NUMBER() OVER (PARTITION BY m.eg ORDER BY m.forzar DESC, ABS(CHECKSUM(m.eg, m.sesion))),
       k = IIF(MAX(m.forzar) OVER (PARTITION BY m.eg) = 1 AND ROUND(m.pct * m.n / 100.0, 0) < 1, 1, CAST(ROUND(m.pct * m.n / 100.0, 0) AS INT))
INTO #m2 FROM #m m;
INSERT INTO dbo.Asistencia (id, estudianteGrupo, sesion) SELECT idAsistencia, eg, sesion FROM #m2;
DECLARE @base INT = (SELECT ISNULL(MAX(codigo), 0) FROM dbo.DetalleAsistencia);
INSERT INTO dbo.DetalleAsistencia (id, codigo, asistencia, asistio, razonCausa, fechaHoraInicio, fechaHoraFin, toma, registradoPorEstudiante, fechaRegistroUtc)
SELECT NEWID(), @base + ROW_NUMBER() OVER (ORDER BY m.fechaHoraInicio, m.eg), m.idAsistencia,
       IIF(m.rn <= m.k + m.ex, 0, 1),
       CASE WHEN m.rn <= m.k THEN @rcSJC WHEN m.rn <= m.k + m.ex THEN @rcEX ELSE @rcAN END,
       m.fechaHoraInicio, m.fechaHoraFin, m.idToma, IIF(m.esQr = 1 AND m.rn > m.k + m.ex, 1, 0), DATEADD(MINUTE, 20, m.fechaHoraInicio)
FROM #m2 m;
UPDATE ta SET totalAusentesMarcados = x.aus FROM dbo.TomaAsistencia ta
JOIN (SELECT toma, aus = SUM(IIF(asistio = 0, 1, 0)) FROM dbo.DetalleAsistencia GROUP BY toma) x ON x.toma = ta.id;
COMMIT TRANSACTION;

